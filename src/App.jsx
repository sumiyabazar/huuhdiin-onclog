/* ============================================================
   ГОЛ APP
   ============================================================ */
export default function App() {
  const [view, setView] = useState('landing');
  const [formData, setFormData] = useState(null);
  const [report, setReport] = useState(null);
  const [orderCode, setOrderCode] = useState(null);

  // URL шалгах — /admin байх юм бол админ хуудас руу
  useEffect(() => {
    const checkUrl = () => {
      if (window.location.hash === '#admin' || window.location.pathname.endsWith('/admin')) {
        setView('admin');
      }
    };
    checkUrl();
    window.addEventListener('hashchange', checkUrl);
    return () => window.removeEventListener('hashchange', checkUrl);
  }, []);

  // Хүлээгдэж байсан захиалга байгаа эсэхийг шалгах
  useEffect(() => {
    if (view !== 'landing') return;
    try {
      const pending = localStorage.getItem('pendingOrder');
      if (pending) {
        const data = JSON.parse(pending);
        setFormData(data.formData);
        setOrderCode(data.code);
        setView('waiting');
      }
    } catch (e) {}
  }, []);

  const handleStart = () => setView('form');
  const handleBackToLanding = () => {
    window.location.hash = '';
    setView('landing');
  };

  const handleFormSubmit = (data) => {
    setFormData(data);
    setView('payment');
  };

  // Төлбөр баталгаажуулах товч → захиалгын код үүсгэж "хүлээх" дэлгэц рүү
  const handlePaymentSuccess = async () => {
    // 6-оронтой код үүсгэх
    const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
    let code = '';
    for (let i = 0; i < 6; i++) code += chars[Math.floor(Math.random() * chars.length)];

    try {
      // Supabase-д захиалга илгээх
      await createOrder({ ...formData, code });
      // Браузерт хадгалах (хуудас дахин нээгдэхэд сэргэх)
      try { localStorage.setItem('pendingOrder', JSON.stringify({ formData, code })); } catch (e) {}
      setOrderCode(code);
      setView('waiting');
    } catch (error) {
      alert('Сүлжээний алдаа: Захиалга илгээж чадсангүй. Интернетээ шалгаад дахин оролдоно уу.\n\n' + error.message);
    }
  };

  // Хэрэглэгч "Шалгах" товч дарах
  const handleCheckApproval = async () => {
    try {
      const status = await checkOrderStatus(orderCode);
      if (status === 'approved') {
        // Зөвшөөрөгдсөн — тайлан үүсгэх
        setView('loading');
        setTimeout(() => {
          const r = generateReport(formData);
          setReport(r);
          try { localStorage.removeItem('pendingOrder'); } catch (e) {}
          setView('report');
        }, 3000);
      } else if (status === null) {
        alert('Таны захиалга олдсонгүй. Дахин захиалга өгнө үү.');
      } else {
        alert('Таны төлбөр хараахан баталгаажаагүй байна. 5-30 минутын дараа дахин шалгана уу.');
      }
    } catch (e) {
      alert('Сүлжээний алдаа гарлаа. Интернетээ шалгана уу.');
    }
  };

  const handleCancel = () => {
    if (!confirm('Захиалгаа цуцлах уу? Шинээр захиалга өгөх шаардлагатай болно.')) return;
    try { localStorage.removeItem('pendingOrder'); } catch (e) {}
    setFormData(null);
    setOrderCode(null);
    setView('landing');
  };

  const handleRestart = () => {
    setFormData(null);
    setReport(null);
    setOrderCode(null);
    try { localStorage.removeItem('pendingOrder'); } catch (e) {}
    setView('form');
  };

  return (
    <>
      <FontInjector />
      {view === 'landing' && <LandingPage onStart={handleStart} />}
      {view === 'form' && <FormPage onSubmit={handleFormSubmit} onBack={handleBackToLanding} initial={formData} />}
      {view === 'payment' && formData && <PaymentPage formData={formData} onSuccess={handlePaymentSuccess} onBack={() => setView('form')} />}
      {view === 'waiting' && formData && orderCode && (
        <WaitingPage orderCode={orderCode} formData={formData} onCheckApproval={handleCheckApproval} onCancel={handleCancel} />
      )}
      {view === 'loading' && <LoadingPage />}
      {view === 'report' && report && <ReportPage report={report} onRestart={handleRestart} onBack={() => setView('form')} />}
      {view === 'admin' && <AdminPage onBack={handleBackToLanding} />}
    </>
  );
}
