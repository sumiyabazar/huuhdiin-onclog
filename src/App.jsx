  const AUTH_DURATION = 30 * 24 * 60 * 60 * 1000; // 30 хоног

  // Хадгалсан нэвтрэлтийг шалгах
  const checkSavedAuth = () => {
    try {
      const saved = localStorage.getItem(AUTH_KEY);
      if (!saved) return false;
      const { time } = JSON.parse(saved);
      if (Date.now() - time < AUTH_DURATION) return true;
      localStorage.removeItem(AUTH_KEY);
      return false;
    } catch (e) { return false; }
  };

  const [password, setPassword] = useState('');
  const [authenticated, setAuthenticated] = useState(checkSavedAuth());
  const [error, setError] = useState('');
  const [orders, setOrders] = useState([]);
  const [inputCode, setInputCode] = useState('');
  const [loading, setLoading] = useState(false);

  // Захиалгууд унших
  const loadData = async () => {
    setLoading(true);
    try {
      const data = await getAllOrders();
      setOrders(data);
    } catch (e) {
      console.error(e);
      alert('Сүлжээний алдаа: ' + e.message);
    }
    setLoading(false);
  };

