const reduceToSingleDigit = (num) => {
  while (num > 9 && num !== 11 && num !== 22 && num !== 33) {
    num = String(num).split('').reduce((sum, d) => sum + parseInt(d, 10), 0);
  }
  return num;
};

const calculateLifePath = (dateStr) => {
  if (!dateStr) return null;
  const digits = dateStr.replace(/\D/g, '').split('').map(Number);
  const sum = digits.reduce((a, b) => a + b, 0);
  return reduceToSingleDigit(sum);
};

// Кирилл нэрийн тоон утга (chaldean system adapted)
const CYRILLIC_MAP = {
  'А':1,'Б':2,'В':3,'Г':4,'Д':5,'Е':6,'Ё':7,'Ж':8,'З':9,
  'И':1,'Й':2,'К':3,'Л':4,'М':5,'Н':6,'О':7,'Ө':8,'П':9,
  'Р':1,'С':2,'Т':3,'У':4,'Ү':5,'Ф':6,'Х':7,'Ц':8,'Ч':9,
  'Ш':1,'Щ':2,'Ъ':3,'Ы':4,'Ь':5,'Э':6,'Ю':7,'Я':8
};

const calculateNameNumber = (name) => {
  if (!name) return null;
  const cleaned = name.toUpperCase().replace(/\s+/g, '');
  let sum = 0;
  for (const ch of cleaned) {
    if (CYRILLIC_MAP[ch]) sum += CYRILLIC_MAP[ch];
    else if (/[A-Z]/.test(ch)) sum += ((ch.charCodeAt(0) - 64 - 1) % 9) + 1;
  }
  if (sum === 0) return null;
  while (sum > 9) sum = String(sum).split('').reduce((a, d) => a + parseInt(d, 10), 0);
  return sum;
};

// Нэрийн эгшиг-гийгүүлэгчийн харьцаа (эрч хүч)
const analyzeNameStructure = (name) => {
  if (!name) return null;
  const vowels = 'АЕЁИОӨУҮЫЭЮЯAEIOU';
  const cleaned = name.toUpperCase().replace(/[\s\-]/g, '');
  let v = 0, c = 0;
  for (const ch of cleaned) {
    if (/[А-ЯӨҮЁA-Z]/i.test(ch)) {
      if (vowels.includes(ch)) v++;
      else c++;
    }
  }
  const total = v + c;
  return { vowels: v, consonants: c, total, vowelRatio: total ? (v / total * 100).toFixed(0) : 0 };
};

