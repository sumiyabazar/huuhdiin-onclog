const generateReport = ({ name, birthDate, gender }) => {
  const lifePath = calculateLifePath(birthDate);
  const nameNumber = calculateNameNumber(name);
  const zodiac = getZodiac(birthDate);
  const nameStruct = analyzeNameStructure(name);
  const d = new Date(birthDate);
  const year = d.getFullYear();
  const month = d.getMonth() + 1;
  const dayOfWeek = d.getDay();
  const animal = getAnimalYear(year);
  const mahbod = getMahbod(name, birthDate);
  const lp = LIFE_PATH_DATA[lifePath] || LIFE_PATH_DATA[1];
  const zd = ZODIAC_DATA[zodiac.key];
  const animalDetail = ANIMAL_DETAIL[animal.key] || ANIMAL_DETAIL.rat;
  const mahbodDetail = MAHBOD_DETAIL[mahbod.key] || MAHBOD_DETAIL.wood;
  const dayData = DAY_OF_WEEK_DATA[dayOfWeek];
  const monthData = MONTH_DATA[month];
  const letterBreakdown = [];
  const cleaned = name.toUpperCase().replace(/\s+/g, '');
  for (const ch of cleaned) {
    const val = CYRILLIC_MAP[ch] || (/[A-Z]/.test(ch) ? ((ch.charCodeAt(0) - 64 - 1) % 9) + 1 : null);
    if (val) letterBreakdown.push({ letter: ch, value: val });
  }
  // Насны тооцоолол
  const today = new Date();
  let age = today.getFullYear() - d.getFullYear();
  const mDiff = today.getMonth() - d.getMonth();
  if (mDiff < 0 || (mDiff === 0 && today.getDate() < d.getDate())) age--;
  const stageKey = age < 3 ? 'infant' : age < 6 ? 'preschool' : age < 12 ? 'primary' : 'teen';
  const ageStage = AGE_STAGES_DATA[stageKey] || AGE_STAGES_DATA.infant;
  const stress = STRESS_STYLES[lifePath] || STRESS_STYLES[1];
  const relationship = RELATIONSHIP_STYLES[lifePath] || RELATIONSHIP_STYLES[1];
  return {
    lifePath, nameNumber, zodiac, nameStruct, animal, mahbod, lp, zd,
    animalDetail, mahbodDetail, dayData, monthData, letterBreakdown,
    age, ageStage, stageKey, stress, relationship,
    name, birthDate, gender, year, month, dayOfWeek
  };
};

